def feature_markdown(feature, team=False):
    lines = ["### " + feature["title"], ""]
    paragraphs = feature["body"] if not team else [feature["role"], feature["body"][0]]
    if team and feature["id"] in {"R03", "R17", "R18", "R24", "R25", "R26", "R27"}:
        paragraphs += feature["body"][1:]
    for paragraph in paragraphs:
        lines += [paragraph, ""]
    lines += ["工程定位  " + feature["files"], ""]
    pictures = feature["proof"]
    if team:
        preferred = {"R07": ["N06", "N09"], "R08": ["N10", "N11", "N12"], "R09": ["H16", "H18", "H19", "H20"],
                     "R10": ["N22", "H12"], "R13": ["N23", "N24"], "R15": ["N31"],
                     "R18": ["N29", "H22"], "R22": ["H24", "H25"], "R23": ["N01", "N35"], "R26": ["N03", "N17"]}
        chosen = preferred.get(feature["id"])
        pictures = [entry for entry in pictures if entry[0] in chosen] if chosen else pictures[:1]
    for key, caption in pictures:
        lines += [f"[FIG {key} {caption}]", ""]
    return "\n".join(lines)


